import os
import sys
import zipfile

ROOT = r"D:\文档\deepseek-harness\default-workspace\PROG2002-A3"
OUT_DIR = os.path.join(ROOT, "submission")

USERNAME = sys.argv[1] if len(sys.argv) > 1 else "24833044"

# Directories that are never useful to a marker and would bloat the archive.
EXCLUDE_DIRS = {
    "node_modules",
    ".angular",
    ".git",
    ".vscode",
    ".idea",
    "__pycache__",
    ".cache",
    "coverage",
    "tmp",
}

# A local .env holds a real database password and must never be submitted.
EXCLUDE_FILES = {".env", ".env.local", "Thumbs.db", ".DS_Store", "npm-debug.log"}

# File extensions left out of the archives.
#
# Markdown is excluded on request. What remains of it in the source tree is the
# boilerplate README that `ng new` generates ("This project was generated using
# Angular CLI...") plus a few explanatory notes; the archives are meant to hold
# the project code. The documentation that carries marks is submitted separately
# (the report, the video and the peer evaluation form).
EXCLUDE_EXTENSIONS = (".md",)

PACKAGES = [
    {
        "zip": f"{USERNAME}A3-clientside.zip",
        "sources": [
            (os.path.join(ROOT, "ng-client"), "clientside"),
        ],
    },
    {
        "zip": f"{USERNAME}A3-adminside.zip",
        "sources": [
            (os.path.join(ROOT, "ng-admin"), "adminside"),
        ],
    },
    {
        "zip": f"{USERNAME}A3-api.zip",
        "sources": [
            (os.path.join(ROOT, "prog2002-a3", "api"), "api"),
            (os.path.join(ROOT, "prog2002-a3", "DEPLOYMENT.md"), None),
            # Extraction and run instructions, placed at the archive root so the
            # marker sees them first.
            (os.path.join(ROOT, "prog2002-a3", "READ-ME-FIRST.txt"), None),
            (os.path.join(ROOT, "prog2002-a3", "tools"), "tools"),
        ],
    },
]


def should_skip_dir(name: str) -> bool:
    return name in EXCLUDE_DIRS or name.startswith(".angular")


def add_tree(archive: zipfile.ZipFile, base_dir: str, prefix: str) -> tuple[int, int]:
    """Add every file under base_dir to the archive. Returns (files, bytes)."""
    files = 0
    total = 0
    for current, dirnames, filenames in os.walk(base_dir):
        # Prune excluded directories in place so os.walk does not descend into them.
        dirnames[:] = [d for d in dirnames if not should_skip_dir(d)]

        for filename in filenames:
            if filename in EXCLUDE_FILES:
                continue
            if filename.endswith((".log", ".tsbuildinfo")):
                continue
            # Markdown is left out of the archives (see EXCLUDE_EXTENSIONS).
            if os.path.splitext(filename)[1].lower() in EXCLUDE_EXTENSIONS:
                continue

            full_path = os.path.join(current, filename)
            relative = os.path.relpath(full_path, base_dir).replace(os.sep, "/")
            arcname = f"{prefix}/{relative}" if prefix else relative

            try:
                archive.write(full_path, arcname)
                files += 1
                total += os.path.getsize(full_path)
            except OSError as err:
                print(f"      skipped {arcname}: {err}")
    return files, total


def build_package(spec: dict) -> None:
    target = os.path.join(OUT_DIR, spec["zip"])
    if os.path.exists(target):
        os.remove(target)

    print(f"  {spec['zip']}")
    total_files = 0
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for source, prefix in spec["sources"]:
            if not os.path.exists(source):
                print(f"      MISSING: {source}")
                continue
            if os.path.isfile(source):
                # A file listed directly (for example DEPLOYMENT.md) is normally
                # kept, but the same extension filter applies so the archives
                # never contain markdown.
                if os.path.splitext(source)[1].lower() in EXCLUDE_EXTENSIONS:
                    print(f"      (excluded by extension) {os.path.basename(source)}")
                    continue
                archive.write(source, os.path.join(prefix or "", os.path.basename(source)))
                total_files += 1
                print(f"      + {os.path.basename(source)}")
                continue
            files, size = add_tree(archive, source, prefix)
            total_files += files
            print(f"      + {prefix}/  ({files} files, {size / 1024 / 1024:.1f} MB uncompressed)")
    print(f"      -> {target}")
    print(f"      -> {os.path.getsize(target) / 1024 / 1024:.1f} MB zipped, {total_files} files")
    print()


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    print()
    print("  PROG2002 A3 - building the submission archives")
    print("  " + "-" * 68)
    for spec in PACKAGES:
        build_package(spec)

    print("  Contents to submit on Blackboard:")
    print(f"    - {USERNAME}A3-clientside.zip")
    print(f"    - {USERNAME}A3-adminside.zip")
    print(f"    - {USERNAME}A3-api.zip")
    print("    - the GitHub repository link")
    print("    - the demonstration video link")
    print("    - the peer evaluation form (emailed to your tutor separately)")
    print("    - the project report (PROG2002_A3_Report_team40.docx)")
    print("    - the GenAI use declaration (inside the report and both READMEs)")
    print()


if __name__ == "__main__":
    main()
